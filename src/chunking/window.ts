import { chunkId, type Chunk, type Chunker } from '../chunk.js';
import { InvalidArgumentError } from '../errors.js';

/** A section windows may not cross: [byteStart, byteEnd, headingPath]. */
export type Section = [number, number, string[]];

const MARKS = ['\n\n', '. ', '! ', '? ', '\n', ' '].map((m) => Buffer.from(m, 'latin1'));

/**
 * Byte windows with overlap, preferring paragraph, then sentence, then line
 * breaks, and never splitting a UTF-8 character.
 *
 * PORT NOTE: this works on the UTF-8 BYTES, exactly as the PHP reference works
 * on PHP strings, so spans, ids and boundaries are identical across languages
 * (checked against a golden fixture generated by the reference).
 */
export class WindowChunker implements Chunker {
  constructor(
    protected readonly target = 1200,
    protected readonly max = 1500,
    protected readonly overlap = 150,
  ) {
    // max >= 4: one UTF-8 character can be 4 bytes.
    if (!Number.isInteger(target) || !Number.isInteger(max) || !Number.isInteger(overlap)
      || target < 1 || max < target || max < 4 || overlap < 0 || overlap >= target) {
      throw new InvalidArgumentError('Chunk sizes need 0 <= overlap < target <= max, and max >= 4.');
    }
  }

  recipe(): string {
    return `${this.name()}@1;target=${this.target};max=${this.max};overlap=${this.overlap}`;
  }

  protected name(): string {
    return 'window';
  }

  chunk(sourceId: string, text: string): Chunk[] {
    const bytes = Buffer.from(text, 'utf8');
    if (bytes.length === 0) {
      return [];
    }
    const lines = lineStarts(bytes);
    const recipe = this.recipe();
    const chunks: Chunk[] = [];
    for (const [start, end, path] of this.sections(bytes)) {
      for (const [s, e] of this.windows(bytes, start, end)) {
        const slice = bytes.subarray(s, e);
        chunks.push({
          id: chunkId(recipe, sourceId, s, e, slice),
          sourceId,
          text: slice.toString('utf8'),
          byteStart: s,
          byteEnd: e,
          lineStart: lineAt(lines, s),
          lineEnd: lineAt(lines, e - 1),
          headingPath: path,
          recipe,
        });
      }
    }

    return chunks;
  }

  protected sections(bytes: Buffer): Section[] {
    return [[0, bytes.length, []]];
  }

  private windows(bytes: Buffer, start: number, end: number): Array<[number, number]> {
    const windows: Array<[number, number]> = [];
    let pos = start;
    while (pos < end) {
      const stop = end - pos <= this.max ? end : this.breakAt(bytes, pos, end);
      windows.push([pos, stop]);
      if (stop >= end) {
        break;
      }
      let next = charBoundary(bytes, Math.max(pos + 1, stop - this.overlap));
      // Start the overlap on a word boundary, never inside a word.
      const space = bytes.indexOf(0x20, next);
      if (this.overlap > 0 && space !== -1 && space < stop) {
        next = space + 1;
      }
      pos = next > pos ? next : stop;
    }

    return windows;
  }

  private breakAt(bytes: Buffer, pos: number, end: number): number {
    const limit = Math.min(pos + this.max, end);
    const floor = pos + Math.floor(this.target / 2);
    const window = bytes.subarray(pos, limit);
    for (const mark of MARKS) {
      const at = window.lastIndexOf(mark);
      if (at !== -1 && pos + at + mark.length > floor) {
        return pos + at + mark.length;
      }
    }

    // Hard cut, on a character boundary.
    return Math.max(pos + 1, charBoundary(bytes, limit));
  }
}

/** Move back to the start of a UTF-8 character. */
function charBoundary(bytes: Buffer, at: number): number {
  while (at > 0 && at < bytes.length && (bytes[at]! & 0xc0) === 0x80) {
    at--;
  }

  return at;
}

function lineStarts(bytes: Buffer): number[] {
  const starts = [0];
  let offset = 0;
  for (;;) {
    const nl = bytes.indexOf(0x0a, offset);
    if (nl === -1) {
      break;
    }
    starts.push(nl + 1);
    offset = nl + 1;
  }

  return starts;
}

/** 1-based line of a byte offset. */
function lineAt(starts: number[], byte: number): number {
  let lo = 0;
  let hi = starts.length - 1;
  while (lo < hi) {
    const mid = Math.floor((lo + hi + 1) / 2);
    if (starts[mid]! <= byte) {
      lo = mid;
    } else {
      hi = mid - 1;
    }
  }

  return lo + 1;
}
